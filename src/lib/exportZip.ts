import JSZip from 'jszip';
import { BRAND_NAME, SITE_URL, PRINT_NOTE, brandLine, provenanceLine } from './exportBrand';

export interface ZipFile {
  name: string;
  desc: string;
  data: string | Uint8Array | Blob;
}

export function buildReadme(opts: { summary: string; files: { name: string; desc: string }[] }): string {
  const bl = brandLine({ summary: opts.summary });
  const fileList = opts.files.map(f => `  ${f.name.padEnd(30)} ${f.desc}`).join('\n');
  return [
    bl,
    '',
    'Files:',
    fileList,
    '',
    provenanceLine('generator'),
    '',
    PRINT_NOTE,
    '',
    `Pattern files generated by ${BRAND_NAME} are free to use; Geist fonts \u00A9 Vercel, SIL OFL 1.1.`,
    `Rigid printed targets: https://${SITE_URL}/targets`,
    '',
  ].join('\n');
}

export async function exportZip(opts: {
  slug: string;
  summary: string;
  files: ZipFile[];
}): Promise<Blob> {
  const zip = new JSZip();
  const readme = buildReadme({ summary: opts.summary, files: opts.files });
  zip.file('README.txt', readme);
  for (const f of opts.files) {
    zip.file(f.name, f.data);
  }
  return zip.generateAsync({ type: 'blob' });
}
