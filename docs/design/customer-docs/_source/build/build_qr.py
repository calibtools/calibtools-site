def serialisable_results(r):
    out = {}
    for k, v in r.items():
        if isinstance(v, np.ndarray):
            out[k] = v.tolist()
        elif isinstance(v, (np.floating, np.integer)):
            out[k] = v.item()
        else:
            out[k] = v
    return out


def build():
    os.makedirs(OUT, exist_ok=True)
    r = simulate_calibration()
    with open(f"{OUT}/{CODE}-results.json", "w") as f:
        json.dump(serialisable_results(r), f, indent=2)

    free = Doc(CODE, REV, DATE, eyebrow="Calibration quality report", title="Camera calibration diagnostic", sn=None,
               subtitle="FREE DIAGNOSTIC · camera solution and capture coverage")
    free.add_page(free_page(r))
    r_free = free.render(f"{OUT}/{CODE}-free")

    full = Doc(CODE, REV, DATE, eyebrow="Calibration quality report", title="Camera calibration diagnostic", sn=None,
               subtitle="FULL REPORT · intrinsics, coverage and uncertainty")
    for page in full_pages(r):
        full.add_page(page)
    r_full = full.render(f"{OUT}/{CODE}-full")
    return r, r_free, r_full


if __name__ == "__main__":
    build()
