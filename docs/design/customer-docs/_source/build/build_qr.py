def rodrigues_from_euler(rx_deg, ry_deg, rz_deg):
    """OpenCV rotation vector for intrinsic X/Y/Z Euler rotations, all in degrees."""
    rx, ry, rz = np.deg2rad([rx_deg, ry_deg, rz_deg])
    Rx = np.array([[1, 0, 0], [0, math.cos(rx), -math.sin(rx)], [0, math.sin(rx), math.cos(rx)]])
    Ry = np.array([[math.cos(ry), 0, math.sin(ry)], [0, 1, 0], [-math.sin(ry), 0, math.cos(ry)]])
    Rz = np.array([[math.cos(rz), -math.sin(rz), 0], [math.sin(rz), math.cos(rz), 0], [0, 0, 1]])
    return cv2.Rodrigues(Rz @ Ry @ Rx)[0]


def rms_error(obj, image, K, D):
    """Fit one pose under K/D and return its actual 2-D RMS residual in pixels."""
    ok, rvec, tvec = cv2.solvePnP(obj, image, K, D, flags=cv2.SOLVEPNP_ITERATIVE)
    if not ok:
        return float("nan")
    projected, _ = cv2.projectPoints(obj, rvec, tvec, K, D)
    delta = projected.reshape(-1, 2) - image.reshape(-1, 2)
    return float(np.sqrt(np.mean(np.sum(delta * delta, axis=1))))


def intrinsic_covariance(obj, rvecs, tvecs, K, D, sse, n_views):
    """Schur-complement covariance for fx, fy, cx, cy, k1, k2, p1, p2, k3.

    cv2.projectPoints supplies the full Jacobian. Per-view pose terms are eliminated as
    nuisance parameters, leaving the intrinsic block that is used for both the correlation
    heatmap and the requested Monte Carlo propagation.
    """
    schur = np.zeros((9, 9), dtype=float)
    for rv, tv in zip(rvecs, tvecs):
        _, jac = cv2.projectPoints(obj, rv, tv, K, D)
        jac = np.asarray(jac, dtype=float).reshape(-1, 15)
        je = jac[:, :6]
        ji = jac[:, 6:15]
        a = ji.T @ ji
        b = ji.T @ je
        c = je.T @ je
        schur += a - b @ np.linalg.pinv(c, rcond=1e-13) @ b.T
    dof = max(1, 2 * len(obj) * n_views - (9 + 6 * n_views))
    sigma2 = sse / dof
    cov = sigma2 * np.linalg.pinv(schur, rcond=1e-12)
    cov = (cov + cov.T) / 2
    # Numerical noise can produce an eigenvalue a few orders below zero. Project to PSD
    # before sampling without changing the observable parameter standard deviations.
    eig, vec = np.linalg.eigh(cov)
    cov_psd = (vec * np.maximum(eig, 0)) @ vec.T
    cov_psd = (cov_psd + cov_psd.T) / 2
    return cov_psd, sigma2, dof


def monte_carlo_corners(K, D, cov):
    """Propagate intrinsic covariance to four 600-mm working-plane image-corner errors."""
    corners = np.array([[0.0, 0.0], [W - 1.0, 0.0], [0.0, H - 1.0], [W - 1.0, H - 1.0]], dtype=np.float64)
    base = cv2.undistortPoints(corners.reshape(-1, 1, 2), K, D).reshape(-1, 2) * 600.0
    mean = np.r_[K[0, 0], K[1, 1], K[0, 2], K[1, 2], D.reshape(-1)[:5]]
    rng = np.random.default_rng(800600)
    samples = rng.multivariate_normal(mean, cov + np.eye(9) * 1e-15, size=6000)
    cloud = []
    for q in samples:
        if q[0] <= 10 or q[1] <= 10:
            continue
        Ks = np.array([[q[0], 0.0, q[2]], [0.0, q[1], q[3]], [0.0, 0.0, 1.0]], dtype=np.float64)
        Ds = q[4:].reshape(1, -1).astype(np.float64)
        xy = cv2.undistortPoints(corners.reshape(-1, 1, 2), Ks, Ds).reshape(-1, 2) * 600.0
        cloud.append(xy - base)
    cloud = np.asarray(cloud)
    # One-sigma radial positional uncertainty after removing the small Monte Carlo mean shift.
    centred = cloud - cloud.mean(axis=0, keepdims=True)
    sigma_mm = np.sqrt(np.mean(np.sum(centred * centred, axis=2), axis=0))
    bias_mm = np.linalg.norm(cloud.mean(axis=0), axis=1)
    return corners, sigma_mm, bias_mm, len(cloud)


def simulate_calibration():
    rng = np.random.default_rng(24072026)
    corners = CP.corner_list(P["rows"], P["cols"], P["sq"])
    obj = np.array([[x, y, 0.0] for _, _, _, x, y in corners], dtype=np.float32).reshape(-1, 1, 3)

    # The simulation's physical camera: 3.45 µm pixels, 12 mm lens, with plausible radial/tangential terms.
    K_true = np.array([[3479.2, 0.0, 1229.7], [0.0, 3476.1, 1026.4], [0.0, 0.0, 1.0]], dtype=np.float64)
    D_true = np.array([[-0.120, 0.080, 0.00055, -0.00040, -0.003]], dtype=np.float64)
    placements = np.array([
        [0.31, 0.30], [0.49, 0.28], [0.67, 0.31],
        [0.29, 0.48], [0.47, 0.47], [0.65, 0.47],
        [0.29, 0.65], [0.46, 0.64],
    ])
    views = []
    image_points = []
    for idx in range(30):
        # Every pose is resampled until the full 176-corner board remains visible. Placements
        # intentionally avoid the lower-right image region, creating the coverage gap diagnosed later.
        for _ in range(3000):
            z = float(rng.uniform(400.0, 900.0))
            base = placements[idx % len(placements)].copy()
            if z < 540:
                base = np.array([0.48, 0.47]) + rng.normal(0, 0.045, 2)
            centre = base + rng.normal(0, 0.024, 2)
            tilt = float(rng.uniform(4.0, 39.5))
            az = float(rng.uniform(0, 2 * math.pi))
            rx, ry = tilt * math.cos(az), tilt * math.sin(az)
            rz = float(rng.uniform(-20.0, 20.0))
            rvec = rodrigues_from_euler(rx, ry, rz)
            R, _ = cv2.Rodrigues(rvec)
            centre_obj = np.array([85.0, 60.0, 0.0])
            camera_centre = np.array([(centre[0] * W - K_true[0, 2]) / K_true[0, 0] * z,
                                      (centre[1] * H - K_true[1, 2]) / K_true[1, 1] * z, z])
            tvec = (camera_centre - R @ centre_obj).reshape(3, 1)
            projected, _ = cv2.projectPoints(obj, rvec, tvec, K_true, D_true)
            xy = projected.reshape(-1, 2)
            if (xy[:, 0].min() > 15 and xy[:, 0].max() < W - 15 and xy[:, 1].min() > 15 and xy[:, 1].max() < H - 15):
                break
        else:
            raise RuntimeError("Unable to place simulated target entirely in frame")

        observed = xy + rng.normal(0.0, 0.10, xy.shape)
        reason = "accepted"
        # Deliberately poor captures: global blur/noise and discrete wrong-corner outliers.
        if idx == 8:
            observed = xy + rng.normal(0.0, 0.72, xy.shape)
            reason = "blur / low contrast"
        if idx == 23:
            observed = xy + rng.normal(0.0, 0.10, xy.shape)
            bad_corners = rng.choice(len(obj), size=20, replace=False)
            observed[bad_corners] += rng.normal(0.0, 2.30, (len(bad_corners), 2))
            reason = "corner outliers"
        normal = R @ np.array([0.0, 0.0, 1.0])
        measured_tilt = math.degrees(math.acos(float(np.clip(normal[2], -1, 1))))
        views.append({"index": idx + 1, "distance_mm": float(np.linalg.norm(camera_centre)),
                      "tilt_deg": measured_tilt, "generation_note": reason})
        image_points.append(observed.astype(np.float32).reshape(-1, 1, 2))

    objects = [obj] * len(image_points)
    # Preliminary all-image solution: the two largest per-view errors are objectively removed.
    _, _, _, _, _, _, _, preliminary_errors = cv2.calibrateCameraExtended(
        objects, image_points, (W, H), None, None, flags=0)
    rejected = set(np.argsort(preliminary_errors.reshape(-1))[-2:].tolist())
    good_idx = [i for i in range(30) if i not in rejected]
    good_objects = [obj for _ in good_idx]
    good_images = [image_points[i] for i in good_idx]
    ret, K, D, rvecs, tvecs, std_i, _, per_view = cv2.calibrateCameraExtended(
        good_objects, good_images, (W, H), None, None, flags=0)

    all_errors = {}
    for local, original in enumerate(good_idx):
        all_errors[original] = float(per_view.reshape(-1)[local])
    for i in rejected:
        all_errors[i] = rms_error(obj, image_points[i], K, D)
    for i, v in enumerate(views):
        v["error_px"] = all_errors[i]
        v["rejected"] = i in rejected
        if v["rejected"]:
            v["rejection_reason"] = v["generation_note"]

    accepted_errors = np.array([all_errors[i] for i in good_idx], dtype=float)
    sse = float(np.sum((accepted_errors ** 2) * len(obj)))
    cov, sigma2, dof = intrinsic_covariance(obj, rvecs, tvecs, K, D, sse, len(good_idx))
    sd_cov = np.sqrt(np.maximum(0.0, np.diag(cov)))
    corr = cov / np.outer(sd_cov, sd_cov)
    corr = np.nan_to_num(corr, nan=0.0)
    np.fill_diagonal(corr, 1.0)

    all_good_points = np.vstack([image_points[i].reshape(-1, 2) for i in good_idx])
    coverage, y_edges, x_edges = np.histogram2d(all_good_points[:, 1], all_good_points[:, 0],
                                                 bins=(8, 10), range=((0, H), (0, W)))
    coverage_pct = float(100 * np.count_nonzero(coverage) / coverage.size)
    pix_corners, uncertainty_mm, bias_mm, mc_n = monte_carlo_corners(K, D, cov)

    f_eq = float(math.sqrt(K[0, 0] * K[1, 1]))
    target_rms_px = S["coordinates"]["rms_um"] / 1000.0 * f_eq / 600.0
    target_max_px = S["coordinates"]["max_um"] / 1000.0 * f_eq / 600.0
    rms = float(ret)
    max_error = float(accepted_errors.max())
    if rms <= 0.20 and coverage_pct >= 75 and len(rejected) <= 2:
        grade = "A"
    elif rms <= 0.30 and coverage_pct >= 55 and len(rejected) <= 3:
        grade = "B"
    elif rms <= 0.50 and coverage_pct >= 35 and len(rejected) <= 5:
        grade = "C"
    else:
        grade = "D"

    return {
        "camera": {"image_width_px": W, "image_height_px": H, "pixel_pitch_um": 3.45, "lens_mm": 12.0,
                   "opencv_version": cv2.__version__},
        "inputs": {"provided_views": 30, "used_views": len(good_idx), "rejected_views": len(rejected),
                   "target": f'{P["part"]} SN {U["sn"]}', "ir_import": "CT-IR-000311"},
        "K": K, "D": D.reshape(-1), "std_cv": std_i.reshape(-1)[:9], "covariance": cov, "correlation": corr,
        "sigma2": sigma2, "dof": dof, "views": views, "accepted_indices": [i + 1 for i in good_idx],
        "rejected_indices": [i + 1 for i in sorted(rejected)], "rms_px": rms, "max_px": max_error,
        "coverage_grid": coverage, "coverage_pct": coverage_pct, "grade": grade, "corners_px": pix_corners,
        "uncertainty_mm": uncertainty_mm, "mc_bias_mm": bias_mm, "monte_carlo_draws": mc_n,
        "target_rms_px": target_rms_px, "target_max_px": target_max_px,
        "target_rms_pct_of_reprojection": 100 * target_rms_px / rms,
        "target_max_pct_of_reprojection": 100 * target_max_px / rms,
        "f_eq_px": f_eq, "true_K": K_true, "true_D": D_true,
    }


