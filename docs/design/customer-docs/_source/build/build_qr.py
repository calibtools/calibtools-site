def intrinsics_table(r):
    K, D = r["K"], r["D"]
    values = [K[0, 0], K[1, 1], K[0, 2], K[1, 2], *D.tolist()]
    labels = ["fx", "fy", "cx", "cy", "k1", "k2", "p1", "p2", "k3"]
    units = ["px", "px", "px", "px", "—", "—", "—", "—", "—"]
    # The Jacobian/Schur standard deviations are the covariance values used for the adjacent matrix.
    rows = [[f'<span class="mono">{a}</span>', (f'{b:.5f}' if abs(b) < 1 else f'{b:.3f}').replace("-", "\u2212"),
             (f'{c:.5f}' if abs(c) < 1 else f'{c:.3f}').replace("-", "\u2212"), u]
            for a, b, c, u in zip(labels, values, r["std_cv"], units)]
    return table([("Parameter", "m"), ("Estimate", "n"), ("Std. deviation", "n"), ("Unit", "c")], rows,
                 cls="plain", widths=["24%", "28%", "30%", "18%"])


